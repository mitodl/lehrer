"""The artifacts ``lehrer features compile`` writes for one scope.

This is the contract in plans/08-feature-manifest.md §4.6. Consumers pin on
:data:`CONTRACT_VERSION`, which moves independently of the manifest schema's
``version``::

    manifest.json            contract_version, group, scope, cell, features,
                             frontends, build_digest, bootstrap_env,
                             secret_settings
    settings/lms.yaml        OL_SETTINGS_DIR-shaped fragment, incl. site_config
    settings/cms.yaml
    bootstrap.yaml           BootstrapSpec holding feature-contributed entries
    mfe_build_env/<mfe>.env  KEY=VALUE, legacy-path MFEs only
    mfe_assets/<mfe>.yaml    resolved slot files and npm bundles, legacy only
    checklist.yaml           services, plugins, commands, runtime config API

Every file is rendered with sorted keys (and lists in feature-name order) so
the same input compiles to the same bytes, which is what lets the output be
committed and drift-checked.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

from lehrer.core.feature_manifest import (
    FeatureManifestError,
    Group,
    ResolvedScope,
    binding_path,
    build_digest,
    merged_build_input,
)

CONTRACT_VERSION = 1

_HEADER = "# Generated by `lehrer features compile`. Do not edit.\n"
MANAGED = (
    "manifest.json",
    "settings",
    "bootstrap.yaml",
    "mfe_build_env",
    "mfe_assets",
    "checklist.yaml",
)
"""Top-level entries compile owns in an output directory."""


def _yaml(data: Any) -> str:
    return _HEADER + yaml.safe_dump(data, sort_keys=True, default_flow_style=False)


def _deep_merge(into: dict[str, Any], value: Mapping[str, Any]) -> None:
    """Merge ``value`` into ``into``. Conflicts were refused at resolve time."""
    for key, item in value.items():
        if isinstance(item, Mapping) and isinstance(into.get(key), dict):
            _deep_merge(into[key], item)
        elif isinstance(item, Mapping):
            into[key] = {}
            _deep_merge(into[key], item)
        else:
            into[key] = item


def settings_fragment(
    group: Group, resolved: ResolvedScope, svc: str
) -> dict[str, Any]:
    """One service's settings fragment, keyed as pydantic-settings reads them.

    An ``operations.features`` key the settings model declares is written
    both at top level (under its alias, if any) and in ``FEATURES``; any
    other only in ``FEATURES``. Under aqueduct the two are separate storage
    and different releases read different ones (§4.6), so one copy would
    miss a reader.
    """
    out: dict[str, Any] = {}
    for feature in resolved.features:
        _deep_merge(out, feature.settings.get(svc, {}))
        for key, value in feature.features.get(svc, {}).items():
            found = group.setting(svc, key)
            name = found.name if found else key
            _deep_merge(out, {"FEATURES": {name: value}})
            if found:
                _deep_merge(out, {found.key: value})
        if svc == "lms":
            _deep_merge(out, feature.site_config)
    return out


def _env_names(data: Any) -> set[str]:
    """Every value of a ``*_env`` field anywhere in ``data``."""
    names: set[str] = set()
    if isinstance(data, Mapping):
        for key, value in data.items():
            if str(key).endswith("_env") and isinstance(value, str):
                names.add(value)
            else:
                names |= _env_names(value)
    elif isinstance(data, list):
        for item in data:
            names |= _env_names(item)
    return names


def emit(group: Group, resolved: ResolvedScope, group_name: str) -> dict[str, str]:
    """Render every artifact for ``resolved``, as relative path -> text."""
    files: dict[str, str] = {}
    for svc in ("lms", "cms"):
        files[f"settings/{svc}.yaml"] = _yaml(settings_fragment(group, resolved, svc))

    bootstrap = resolved.bootstrap().model_dump(exclude_defaults=True)
    files["bootstrap.yaml"] = _yaml(bootstrap)

    legacy = sorted(
        mfe for mfe, b in resolved.frontends.items() if binding_path(b) == "legacy"
    )
    for mfe in legacy:
        # The same merged input build_digest hashes, so the digest in
        # manifest.json always describes these two files.
        merged = merged_build_input(resolved, mfe)
        for key, value in merged["env"].items():
            if "\n" in value:
                msg = f"{resolved.scope}: mfe_build_env {mfe} {key} contains a newline"
                raise FeatureManifestError(msg)
        files[f"mfe_build_env/{mfe}.env"] = "".join(
            f"{key}={value}\n" for key, value in sorted(merged["env"].items())
        )
        files[f"mfe_assets/{mfe}.yaml"] = _yaml(
            {
                "contract_version": CONTRACT_VERSION,
                "extra_slot_files": merged["extra_slot_files"],
                "extra_npm_bundles": merged["extra_npm_bundles"],
            }
        )

    secret_settings = sorted(
        {s for f in resolved.features for s in f.requires.secret_settings}
    )
    bootstrap_env = sorted(_env_names(bootstrap))
    runtime_config = [f.feature for f in resolved.features if f.site_config]
    files["checklist.yaml"] = _yaml(
        {
            "contract_version": CONTRACT_VERSION,
            "scope": resolved.scope,
            "services": sorted(
                {s for f in resolved.features for s in f.requires.services}
            ),
            "plugins": sorted(
                {
                    p
                    for f in resolved.features
                    for p in [
                        *f.requires.plugins,
                        *(
                            [group.definitions[f.feature].model.provided_by]
                            if group.definitions[f.feature].model.provided_by
                            else []
                        ),
                    ]
                }
            ),
            "commands": [
                {"feature": f.feature, **c.model_dump()}
                for f in resolved.features
                for c in f.commands
            ],
            "runtime_config_api": {
                "needed": bool(runtime_config),
                "features": runtime_config,
                # Upstream reads these settings through
                # configuration_helpers.get_value, so a SiteConfiguration row
                # holding the same key replaces the compiled value whole.
                "site_configuration_overrides": bool(runtime_config),
            },
            "secret_settings": secret_settings,
            "bootstrap_env": bootstrap_env,
        }
    )
    files["manifest.json"] = (
        json.dumps(
            {
                "contract_version": CONTRACT_VERSION,
                "group": group_name,
                "scope": resolved.scope,
                "generated_from": {
                    "cell": {
                        "release": resolved.cell.release,
                        "deployment": resolved.cell.deployment,
                    },
                    "features": {f.feature: f.params for f in resolved.features},
                },
                "frontends": {
                    mfe: binding if isinstance(binding, str) else binding.model_dump()
                    for mfe, binding in resolved.frontends.items()
                },
                "build_digest": {mfe: build_digest(resolved, mfe) for mfe in legacy},
                "bootstrap_env": bootstrap_env,
                "secret_settings": secret_settings,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    return files


def _is_compile_output(out: Path) -> bool:
    """Whether ``out`` holds a ``manifest.json`` that compile wrote.

    A web or static tree often has a ``manifest.json`` of its own, so the
    name alone does not mark a directory as compile's.
    """
    try:
        manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    except (FileNotFoundError, IsADirectoryError, json.JSONDecodeError):
        return False
    return isinstance(manifest, dict) and {"contract_version", "generated_from"} <= set(
        manifest
    )


def write(files: Mapping[str, str], out: Path) -> None:
    """Write ``files`` under ``out``, replacing a previous compile's output.

    Refuses a non-empty directory unless it holds a ``manifest.json`` compile
    wrote, so a mistyped ``--out`` cannot delete anything compile did not
    write. Within a previous output only the entries in :data:`MANAGED` are
    replaced, so an MFE dropped from the scope does not leave a stale file
    behind.
    """
    if out.exists() and not out.is_dir():
        msg = f"{out} is not a directory"
        raise FeatureManifestError(msg)
    if out.exists() and any(out.iterdir()) and not _is_compile_output(out):
        msg = (
            f"{out} is not empty and holds no manifest.json from "
            "`lehrer features compile`; refusing to overwrite it"
        )
        raise FeatureManifestError(msg)
    for name in MANAGED:
        target = out / name
        if target.is_dir():
            for path in sorted(target.rglob("*"), reverse=True):
                path.rmdir() if path.is_dir() else path.unlink()
            target.rmdir()
        elif target.exists():
            target.unlink()
    for relative, text in sorted(files.items()):
        path = out / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
